    def test_phuc_hoi_schema_co_dinh_khong_am_tham_mo_kho_hien_hanh(self):
        """V13 A3: snapshot (A) → kho hiện hành thêm B → phục hồi kho.sqlite vào thư mục mới, cùng schema cố định:
        từ chối, schema hiện hành giữ nguyên (không drop); schema mới trống: nạp đúng snapshot; mở lại không nạp lần hai."""
        from types import SimpleNamespace
        from unittest.mock import patch

        from kho_tri_thuc.ha_tang.ket_noi import _trang_thai_schema, kiem_dich_phuc_hoi
        from kho_tri_thuc.ha_tang.primitives import DataError
        from kho_tri_thuc.ha_tang.sao_chep_bang import chep_pg_sang_sqlite

        log = "INSERT INTO activity_log(module,action,subject_id,actor,event_at,recorded_at,details_json) VALUES ('M1',?,'s','MO_PHONG_A3','2026-09-01T00:00:00Z','2026-09-01T00:00:00Z','{}')"
