        with tempfile.TemporaryDirectory() as tmp:
            dau = Path(tmp) / "lan-dau" / "kho.sqlite"
            dau.parent.mkdir()
            src = database.connect(dau)
            src.execute("INSERT INTO workspace_meta VALUES ('entity_id','PLHN_FIXTURE')")
