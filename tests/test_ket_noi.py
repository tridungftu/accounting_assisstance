                self.assertTrue(phuc_hoi.is_file())  # snapshot không bị đổi tên/bỏ qua
                self.assertEqual(hanh_dong(live), ["A", "B"])  # schema hiện hành nguyên vẹn
                # schema đích mới (cố định hoặc auto): nạp đúng snapshot
                moi = "t_" + uuid.uuid4().hex[:10]
                self.assertEqual(_trang_thai_schema(self.dsn, moi), (False, False))
