        try:
            a.execute("BEGIN IMMEDIATE")
            a.execute("INSERT INTO workspace_meta VALUES ('k','a')")
            seen = {}

            def ghi():
                b.execute("BEGIN IMMEDIATE")  # phải chờ a
                seen["row"] = b.execute("SELECT value FROM workspace_meta WHERE key='k'").fetchone()
                b.rollback()

            t = threading.Thread(target=ghi)
            t.start()
            time.sleep(0.3)
            self.assertNotIn("row", seen)  # b vẫn đang chờ khóa
            a.commit()
            t.join(5)
            self.assertEqual(seen["row"][0], "a")
        finally:
            a.close()
            b.close()

