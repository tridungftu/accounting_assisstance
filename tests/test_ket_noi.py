class DichSqlTests(unittest.TestCase):
    def test_placeholder_va_phan_tram(self):
        self.assertEqual(dich_sql("SELECT a FROM t WHERE b=? AND c LIKE 'CFO:%'"), "SELECT a FROM t WHERE b=%s AND c ILIKE 'CFO:%%' ESCAPE ''")
        self.assertEqual(dich_sql("SELECT a FROM t WHERE c LIKE 'CFO:%'"), "SELECT a FROM t WHERE c ILIKE 'CFO:%' ESCAPE ''")  # không tham số → giữ %

    def test_dau_hoi_trong_chuoi_khong_bi_doi(self):
        self.assertEqual(dich_sql("SELECT '?' AS q, x FROM t WHERE y=?"), "SELECT '?' AS q, x FROM t WHERE y=%s")

    def test_insert_or_ignore(self):
        self.assertEqual(dich_sql("INSERT OR IGNORE INTO t VALUES (?,?)"), "INSERT INTO t VALUES (%s,%s) ON CONFLICT DO NOTHING")

    def test_begin_pragma(self):
        self.assertEqual(dich_sql("BEGIN IMMEDIATE"), "BEGIN")
        self.assertIsNone(dich_sql("PRAGMA foreign_keys=ON"))

    def test_max_min_hai_doi_so(self):
        self.assertEqual(dich_sql("UPDATE t SET a=MAX(a,?) WHERE id=?"), "UPDATE t SET a=GREATEST(a,%s) WHERE id=%s")
        self.assertEqual(dich_sql("SELECT MAX(revision) FROM t"), "SELECT MAX(revision) FROM t")
        self.assertEqual(dich_sql("SELECT MIN(a, b), MAX(c) FROM t"), "SELECT LEAST(a, b), MAX(c) FROM t")

    def test_ddl_kieu_cot_va_rowid(self):
        out = dich_ddl("CREATE TABLE issues (id INTEGER PRIMARY KEY, attempt_id TEXT NOT NULL REFERENCES attempts(id), n INTEGER, r REAL, b BLOB)")
        self.assertEqual(len(out), 1)
        self.assertIn("id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", out[0])
        self.assertIn('text COLLATE "C"', out[0])
        self.assertIn("REFERENCES attempts(id) DEFERRABLE INITIALLY IMMEDIATE", out[0])
        self.assertIn("double precision", out[0])
        self.assertIn("bytea", out[0])
        self.assertTrue(out[0].rstrip().endswith(", rowid bigint GENERATED ALWAYS AS IDENTITY)"))

    def test_ddl_trigger_epoch(self):
        out = dich_ddl("CREATE TRIGGER knowledge_epoch_knowledge_versions_insert AFTER INSERT ON knowledge_versions BEGIN UPDATE knowledge_epoch SET revision=lower(hex(randomblob(16))) WHERE id=1; END")
        self.assertEqual(out, ["CREATE TRIGGER knowledge_epoch_knowledge_versions_insert AFTER INSERT ON knowledge_versions FOR EACH STATEMENT EXECUTE FUNCTION knowledge_epoch_bump()"])

    def test_returning_chu_thich_va_escape(self):
        self.assertEqual(dich_sql("INSERT OR IGNORE INTO t VALUES (?) RETURNING id"), "INSERT INTO t VALUES (%s) ON CONFLICT DO NOTHING RETURNING id")
        self.assertEqual(dich_sql("INSERT OR IGNORE INTO t VALUES (?) -- ghi chú"), "INSERT INTO t VALUES (%s) ON CONFLICT DO NOTHING")
        self.assertIn("b=%s", dich_sql("SELECT /* it's */ a FROM t WHERE b=?"))
        self.assertEqual(dich_sql("SELECT 1 FROM t WHERE a LIKE ?"), "SELECT 1 FROM t WHERE a ILIKE %s ESCAPE ''")
        with self.assertRaises(ValueError):
            dich_sql("SELECT 1 FROM t WHERE a LIKE b")

